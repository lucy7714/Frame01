var sparkles = svgSparkles.map(function(p) {
  return { x: p[0], y: p[1], cx: 0, cy: 0, tx: 0, ty: 0, cs: 1, ts: 1 };
});

var vertSrc = 'attribute vec2 a_pos;\nattribute float a_scale;\nuniform vec2 u_res;\nuniform float u_size;\nvoid main() {\n  vec2 p = (a_pos / u_res) * 2.0 - 1.0;\n  p.y = -p.y;\n  gl_Position = vec4(p, 0.0, 1.0);\n  gl_PointSize = u_size * max(a_scale, 0.0);\n}';

var fragSrc = 'precision mediump float;\nuniform vec3 u_color;\nvoid main() {\n  vec2 c = (gl_PointCoord - 0.5) * 2.0;\n  float n = 0.45;\n  float r = 0.6;\n  // Vertical spike\n  float v = pow(abs(c.x / 0.25), n) + pow(abs(c.y / r), n);\n  // Horizontal spike\n  float h = pow(abs(c.x / r), n) + pow(abs(c.y / 0.25), n);\n  float inside = min(v, h);\n  if (inside > 1.0) discard;\n  float alpha = smoothstep(1.0, 0.0, inside);\n  alpha = pow(alpha, 0.3);\n  gl_FragColor = vec4(u_color, alpha);\n}';

function makeShader(src, type) {
  var s = gl.createShader(type);
  gl.shaderSource(s, src);
  gl.compileShader(s);
  return s;
}

var prog = gl.createProgram();
gl.attachShader(prog, makeShader(vertSrc, gl.VERTEX_SHADER));
gl.attachShader(prog, makeShader(fragSrc, gl.FRAGMENT_SHADER));
gl.linkProgram(prog);
gl.useProgram(prog);

var posBuf = gl.createBuffer();
var scaleBuf = gl.createBuffer();
var posLoc = gl.getAttribLocation(prog, 'a_pos');
var scaleLoc = gl.getAttribLocation(prog, 'a_scale');
var resLoc = gl.getUniformLocation(prog, 'u_res');
var sizeLoc = gl.getUniformLocation(prog, 'u_size');
var colorLoc = gl.getUniformLocation(prog, 'u_color');
gl.enableVertexAttribArray(posLoc);
gl.enableVertexAttribArray(scaleLoc);

var mx = 0, my = 0;
var svx = 0, svy = 0, spd = 0;

document.addEventListener('mousemove', function(e) {
  var r = canvas.getBoundingClientRect();
  var nx = e.clientX - r.left;
  var ny = e.clientY - r.top;
  var dx = nx - mx;
  var dy = ny - my;
  spd = Math.sqrt(dx * dx + dy * dy);
  svx += (dx - svx) * 0.15;
  svy += (dy - svy) * 0.15;
  mx = nx;
  my = ny;
});

function update() {
  var smoothLen = Math.sqrt(svx * svx + svy * svy);
  var speedFactor = Math.min(1.0, spd / 8.0);
  var tailLen = 20 + speedFactor * 160;

  for (var i = 0; i < sparkles.length; i++) {
    var s = sparkles[i];
    var dx = s.x - mx;
    var dy = s.y - my;
    var affected = false;

    if (smoothLen > 0.3) {
      var vnx = svx / smoothLen;
      var vny = svy / smoothLen;
      var along = -(dx * vnx + dy * vny);
      var perpDot = dx * -vny + dy * vnx;
      var perpDist = Math.abs(perpDot);
      var perpSign = perpDot > 0 ? 1 : -1;

      if (!affected && along > -HEAD_RADIUS && along < HEAD_RADIUS) {
        var angle = Math.atan2(dy, dx);
        var pinch = Math.abs(Math.sin(angle * 2)) * 0.4;
        var manhDist = (Math.abs(dx) + Math.abs(dy)) / HEAD_RADIUS;
        var threshold = 1.0 - pinch;
        if (manhDist < threshold) {
          var norm = manhDist / threshold;
          var ease = 1.0 - Math.pow(norm, 3);
          s.tx = -vny * perpSign * PUSH * ease;
          s.ty = vnx * perpSign * PUSH * ease;
          s.ts = 1.0;
          affected = true;
        }
      }

      if (!affected && along > 0 && along < tailLen && perpDist < FALLOFF_RADIUS * 0.4) {
        var alongFalloff = (1.0 - Math.pow(along / tailLen, 1.5)) * speedFactor;
        var perpFalloff = 1.0 - Math.pow(perpDist / (FALLOFF_RADIUS * 0.4), 2);
        var ease = alongFalloff * perpFalloff;
        s.tx = -vny * perpSign * PUSH * ease;
        s.ty = vnx * perpSign * PUSH * ease;
        s.ts = 1.0;
        affected = true;
      }
    }

    if (!affected) { s.ts = 1.0; s.tx = 0; s.ty = 0; }
    s.cs += (s.ts - s.cs) * 0.3;
    s.cx += (s.tx - s.cx) * RESPONSE;
    s.cy += (s.ty - s.cy) * RESPONSE;
  }
}

function render() {
  update();
  gl.clearColor(0, 0, 0, 1);
  gl.clear(gl.COLOR_BUFFER_BIT);
  gl.enable(gl.BLEND);
  gl.blendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA);

  var pos = new Float32Array(sparkles.length * 2);
  var scales = new Float32Array(sparkles.length);
  for (var i = 0; i < sparkles.length; i++) {
    pos[i * 2]     = sparkles[i].x + sparkles[i].cx;
    pos[i * 2 + 1] = sparkles[i].y + sparkles[i].cy;
    scales[i]      = Math.max(0, sparkles[i].cs);
  }

  gl.bindBuffer(gl.ARRAY_BUFFER, posBuf);
  gl.bufferData(gl.ARRAY_BUFFER, pos, gl.DYNAMIC_DRAW);
  gl.vertexAttribPointer(posLoc, 2, gl.FLOAT, false, 0, 0);

  gl.bindBuffer(gl.ARRAY_BUFFER, scaleBuf);
  gl.bufferData(gl.ARRAY_BUFFER, scales, gl.DYNAMIC_DRAW);
  gl.vertexAttribPointer(scaleLoc, 1, gl.FLOAT, false, 0, 0);

  gl.uniform2f(resLoc, canvas.width, canvas.height);
  gl.uniform1f(sizeLoc, POINT_SIZE);
  gl.uniform3f(colorLoc, 1.0, 1.0, 1.0);
  gl.drawArrays(gl.POINTS, 0, sparkles.length);
  requestAnimationFrame(render);
}

render();